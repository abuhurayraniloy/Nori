use crate::doc::ExtractError;
use crate::rules::{Rules, CODE_FILE_NAMES};
use nori_core::options::IndexOptions;
use std::fs::File;
use std::io::Read;
use std::path::{Path, PathBuf};

/// A stretch of code within a file: its text content and 1-based line or cell boundaries.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodePiece {
    pub text: String,
    pub first: usize,
    pub last: usize,
}

/// A parsed source code file, document, or Jupyter notebook.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodeFile {
    pub pieces: Vec<CodePiece>,
    pub title: String,
    pub repo: Option<String>,
    pub lines: usize,
    pub cells: Option<usize>,
}

/// Extractor for source code files and Jupyter notebooks.
pub struct CodeExtractor;

impl CodeExtractor {
    /// 4,000 characters maximum per piece (~2,048 tokens context cutoff for EmbeddingGemma).
    pub const LONGEST_PIECE: usize = 4000;

    pub const CLOSERS: &[&str] = &[
        "end", "fi", "done", "esac", "@end", "#endif", "end;", "end)",
    ];

    /// Reads and prepares a code file or notebook into indexed stretches.
    pub fn read(path: &Path, options: &IndexOptions) -> Result<CodeFile, ExtractError> {
        let mut file = File::open(path)?;
        let mut data = Vec::new();
        file.read_to_end(&mut data)?;

        let (repo, title) = Self::place(path);
        let ext = path
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("")
            .to_lowercase();

        if ext == "ipynb" {
            let cell_texts = Self::notebook_cells(&data)?;
            let text = cell_texts.join("\n");
            if text.len() > options.max_code_bytes {
                return Err(ExtractError::Unreadable(format!(
                    "cells over {} MB",
                    options.max_code_bytes >> 20
                )));
            }
            Self::check(&text, true)?;
            let pieces = Self::cells(&cell_texts, options.code_stretch);
            let lines = Self::line_count(&text);
            let cells_count = cell_texts.len();
            return Ok(CodeFile {
                pieces,
                title,
                repo,
                lines,
                cells: Some(cells_count),
            });
        }

        // Non-text binary detection: null bytes in first 8,000 bytes
        let check_len = data.len().min(8000);
        if data[..check_len].contains(&0) {
            return Err(ExtractError::Unreadable("not text".to_string()));
        }

        let text = match String::from_utf8(data) {
            Ok(s) => s,
            Err(e) => e.into_bytes().into_iter().map(|b| b as char).collect(),
        };

        let is_source = crate::rules::SOURCE_EXTENSIONS.contains(&ext.as_str());
        Self::check(&text, is_source)?;

        let pieces = Self::lines(&text, options.code_stretch);
        let lines = Self::line_count(&text);

        Ok(CodeFile {
            pieces,
            title,
            repo,
            lines,
            cells: None,
        })
    }

    /// Validates code quality and safety: rejects private keys, generator boilerplate, and minified bundles.
    pub fn check(text: &str, source: bool) -> Result<(), ExtractError> {
        if text.contains("PRIVATE KEY-----") {
            return Err(ExtractError::Unreadable("holds a private key".to_string()));
        }
        if !source {
            return Ok(());
        }

        let top: String = text.chars().take(1000).collect();
        for mark in &[
            "DO NOT EDIT",
            "@generated",
            "Code generated by",
            "Autogenerated by",
            "Generated by the protocol",
        ] {
            if top.contains(mark) {
                return Err(ExtractError::Unreadable(format!(
                    "made by a program (\"{mark}\")"
                )));
            }
        }

        // Minified bundle detection
        let lines = Self::line_count(text).max(1);
        let characters = text.chars().count();
        if characters / lines > 300
            && text.split('\n').any(|line| line.chars().count() > 3000)
        {
            return Err(ExtractError::Unreadable(format!(
                "minified ({} characters a line)",
                characters / lines
            )));
        }

        Ok(())
    }

    /// Counts newlines efficiently.
    pub fn line_count(text: &str) -> usize {
        let count = text.bytes().filter(|&b| b == b'\n').count();
        if text.ends_with('\n') || text.is_empty() {
            count
        } else {
            count + 1
        }
    }

    /// Slices source code into syntactic stretches of whole lines with indentation-aware snapping.
    pub fn lines(text: &str, size: usize) -> Vec<CodePiece> {
        let raw_lines: Vec<&str> = text
            .split('\n')
            .map(|l| l.strip_suffix('\r').unwrap_or(l))
            .collect();

        let mut lines = raw_lines;
        if lines.last().map(|l| l.is_empty()).unwrap_or(false) {
            lines.pop();
        }

        let count = lines.len();
        if count == 0 {
            return Vec::new();
        }

        let mut offsets = Vec::with_capacity(count + 1);
        offsets.push(0);
        for line in &lines {
            offsets.push(offsets.last().unwrap() + line.chars().count() + 1);
        }

        let blank = |idx: usize| lines[idx].chars().all(|c| c.is_whitespace());
        let starts_block = |idx: usize| -> bool {
            let line = lines[idx];
            let Some(first) = line.chars().next() else {
                return false;
            };
            if first.is_whitespace() {
                return false;
            }
            let trimmed = line.trim();
            if "})]".contains(first) || Self::CLOSERS.contains(&trimmed) {
                return false;
            }
            true
        };

        let mut pieces = Vec::new();
        let mut start = 0;

        while start < count {
            while start < count && blank(start) {
                start += 1;
            }
            if start >= count {
                break;
            }

            let mut end = start + 1;
            while end < count && (offsets[end + 1] - offsets[start]) <= size {
                end += 1;
            }

            let mut natural = end >= count;
            if !natural {
                let floor = offsets[start] + size * 2 / 5;

                // Priority 1: new block after a blank line
                let mut cut = None;
                let mut line = end;
                while line > start + 1 && offsets[line] >= floor {
                    if starts_block(line) && blank(line - 1) {
                        cut = Some(line);
                        break;
                    }
                    line -= 1;
                }

                // Priority 2: any blank line or new block
                if cut.is_none() {
                    let mut line = end;
                    while line > start + 1 && offsets[line] >= floor {
                        if blank(line - 1) || starts_block(line) {
                            cut = Some(line);
                            break;
                        }
                        line -= 1;
                    }
                }

                if let Some(c) = cut {
                    end = c;
                    natural = true;
                }
            }

            let mut last = end;
            while last > start + 1 && blank(last - 1) {
                last -= 1;
            }

            let mut body = lines[start..last].join("\n");
            if body.chars().count() > Self::LONGEST_PIECE {
                body = body.chars().take(Self::LONGEST_PIECE).collect();
            }

            pieces.push(CodePiece {
                text: body,
                first: start + 1,
                last,
            });

            start = if natural {
                end
            } else {
                (end.saturating_sub(2)).max(start + 1)
            };
        }

        pieces
    }

    /// Extracts cells from Jupyter notebook JSON data (supporting both nbformat 3 and 4).
    pub fn notebook_cells(data: &[u8]) -> Result<Vec<String>, ExtractError> {
        let val: serde_json::Value = serde_json::from_slice(data)
            .map_err(|e| ExtractError::Unreadable(format!("not a notebook: {e}")))?;

        let cells_val = val.get("cells").and_then(|v| v.as_array()).or_else(|| {
            val.get("worksheets")
                .and_then(|w| w.as_array())
                .and_then(|arr| arr.first())
                .and_then(|first| first.get("cells"))
                .and_then(|c| c.as_array())
        });

        let Some(cells) = cells_val else {
            return Ok(Vec::new());
        };

        let mut result = Vec::with_capacity(cells.len());
        for cell in cells {
            let source_val = cell.get("source").or_else(|| cell.get("input"));
            let text = match source_val {
                Some(serde_json::Value::Array(arr)) => {
                    let mut joined = String::new();
                    for item in arr {
                        if let Some(s) = item.as_str() {
                            joined.push_str(s);
                        }
                    }
                    joined
                }
                Some(serde_json::Value::String(s)) => s.clone(),
                _ => String::new(),
            };
            result.push(text);
        }
        Ok(result)
    }

    /// Combines notebook cells into stretches of up to `size` characters.
    pub fn cells(cells: &[String], size: usize) -> Vec<CodePiece> {
        let mut pieces = Vec::new();
        let mut text = String::new();
        let mut first = 0;
        let mut last = 0;

        for (index, cell) in cells.iter().enumerate() {
            let body = cell.trim();
            if body.is_empty() {
                continue;
            }
            let number = index + 1;
            if body.chars().count() > size {
                if !text.is_empty() {
                    pieces.push(CodePiece {
                        text: std::mem::take(&mut text),
                        first,
                        last,
                    });
                }
                for p in Self::lines(body, size) {
                    pieces.push(CodePiece {
                        text: p.text,
                        first: number,
                        last: number,
                    });
                }
                continue;
            }

            if !text.is_empty() && text.chars().count() + 2 + body.chars().count() > size {
                pieces.push(CodePiece {
                    text: std::mem::take(&mut text),
                    first,
                    last,
                });
            }

            if text.is_empty() {
                first = number;
                text = body.to_string();
            } else {
                text.push_str("\n\n");
                text.push_str(body);
            }
            last = number;
        }

        if !text.is_empty() {
            pieces.push(CodePiece { text, first, last });
        }

        pieces
    }

    /// Generates a single-line summary of a code stretch for search result listings.
    pub fn summary(text: &str) -> String {
        let lines: Vec<&str> = text
            .split('\n')
            .map(|l| l.strip_suffix('\r').unwrap_or(l).trim())
            .filter(|l| !l.is_empty())
            .collect();

        // 1. Definition line
        let definition = lines.iter().copied().find(|line| {
            let words: Vec<&str> = line.split_whitespace().take(4).collect();
            words.iter().any(|w| CodeLookup::defines_something(w))
        });

        // 2. Code line (not comments or boilerplate)
        let code = lines.iter().copied().find(|line| {
            !["//", "#", "/*", "*", "--", "\"\"\"", "import ", "from ", "#include", "using ", "package ", "}", ")", "@"]
                .iter()
                .any(|prefix| line.starts_with(prefix))
        });

        let chosen = definition
            .or(code)
            .or_else(|| lines.first().copied())
            .unwrap_or("");

        let chars: Vec<char> = chosen.chars().collect();
        if chars.len() > 160 {
            let prefix: String = chars.into_iter().take(160).collect();
            format!("{}…", prefix)
        } else {
            chosen.to_string()
        }
    }

    /// Discovers repo root and repo-relative display title.
    pub fn place(path: &Path) -> (Option<String>, String) {
        let mut folder = path.parent();
        let mut repo: Option<PathBuf> = None;

        while let Some(f) = folder {
            if f.join(".git").exists() || Rules::is_project_root(f) {
                repo = Some(f.to_path_buf());
                break;
            }
            folder = f.parent();
        }

        if let Some(r) = repo {
            if let Some(parent) = r.parent() {
                if let Ok(rel) = path.strip_prefix(parent) {
                    let formatted = rel.to_string_lossy().replace('\\', "/");
                    return (Some(r.to_string_lossy().replace('\\', "/")), formatted);
                }
            }
            let repo_str = r.to_string_lossy().replace('\\', "/");
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            return (Some(repo_str.clone()), format!("{}/{}", repo_str, name));
        }

        // Outside repository: take last 2 components
        let comps: Vec<&str> = path.iter().filter_map(|c| c.to_str()).collect();
        let title = if comps.len() >= 2 {
            format!("{}/{}", comps[comps.len() - 2], comps[comps.len() - 1])
        } else {
            comps.last().copied().unwrap_or("").to_string()
        };

        (None, title)
    }

    /// Maps file extension / filename to programming language name.
    pub fn language(path: &Path) -> String {
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
        let ext = path
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("")
            .to_lowercase();

        if let Some(&lang) = LANGUAGES.get(ext.as_str()) {
            return lang.to_string();
        }
        if CODE_FILE_NAMES.contains(&name) || name.starts_with("Dockerfile") {
            return name.to_string();
        }
        if ext.is_empty() {
            "Text".to_string()
        } else {
            ext.to_uppercase()
        }
    }
}

